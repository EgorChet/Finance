/** Patterns for lines built at run time (core labels with numbers or dates inside). `$1` is re-translated. */
const MON: Record<string, string> = {
  Jan: "янв", Feb: "фев", Mar: "мар", Apr: "апр", May: "май", Jun: "июн",
  Jul: "июл", Aug: "авг", Sep: "сен", Oct: "окт", Nov: "ноя", Dec: "дек",
};
const MON_RE = "(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)";

export const RU_PATTERNS: [RegExp, string | ((m: RegExpMatchArray) => string)][] = [
  // "Nov 2026" (labels the server builds)
  [new RegExp(`^${MON_RE} (\\d{4})$`), (m) => `${MON[m[1]]} ${m[2]}`],
  // "12 Nov" / "12 Nov 2026"
  [new RegExp(`^(\\d{1,2}) ${MON_RE}( \\d{4})?$`), (m) => `${m[1]} ${MON[m[2]]}${m[3] ?? ""}`],
  [/^(.+) · partial$/, "$1 · частично"],
  [/^(.+) · in progress$/, "$1 · идёт"],
  [/^(.+) · awaiting statement$/, "$1 · ждём выписку"],
  [/^(.+) · partial snapshot$/, "$1 · частичная выписка"],
  [/^(.+) – (.+)$/, "$1 – $2"],
];
